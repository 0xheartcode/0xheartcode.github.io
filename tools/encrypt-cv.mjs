#!/usr/bin/env node
// Encrypt the CV data into a browser-decryptable blob.
//
//   node tools/encrypt-cv.mjs cv/cv-data.json cv/cv.enc.js "your-passphrase"
//
// Writes `window.CV_BLOB = {...}` to the output file. Only the CIPHERTEXT is
// written, so the output is safe to commit. The plaintext input (cv-data.json)
// is kept out of git via .git/info/exclude. Scheme: PBKDF2(SHA-256) -> AES-256-GCM,
// identical to the decrypt path in cv/index.html.

import { readFileSync, writeFileSync } from 'node:fs';
import { webcrypto as crypto } from 'node:crypto';

const [, , inPath, outPath, passArg] = process.argv;
const pass = passArg ?? process.env.CV_PASS;

if (!inPath || !outPath || !pass) {
  console.error('usage: node tools/encrypt-cv.mjs <in.json> <out.js> <passphrase>');
  console.error('   or: CV_PASS=... node tools/encrypt-cv.mjs <in.json> <out.js>');
  process.exit(1);
}

const ITER = 310000; // PBKDF2 iterations (OWASP-grade for SHA-256)
const plaintext = readFileSync(inPath); // raw bytes of the JSON
const enc = new TextEncoder();
const salt = crypto.getRandomValues(new Uint8Array(16));
const iv = crypto.getRandomValues(new Uint8Array(12));

const baseKey = await crypto.subtle.importKey('raw', enc.encode(pass), 'PBKDF2', false, ['deriveKey']);
const key = await crypto.subtle.deriveKey(
  { name: 'PBKDF2', salt, iterations: ITER, hash: 'SHA-256' },
  baseKey,
  { name: 'AES-GCM', length: 256 },
  false,
  ['encrypt']
);
const ct = new Uint8Array(await crypto.subtle.encrypt({ name: 'AES-GCM', iv }, key, plaintext));

const b64 = (u8) => Buffer.from(u8).toString('base64');
const blob = { v: 1, kdf: 'PBKDF2', hash: 'SHA-256', iter: ITER, salt: b64(salt), iv: b64(iv), ct: b64(ct) };

writeFileSync(outPath, '/* generated by tools/encrypt-cv.mjs - ciphertext only, safe to commit */\n' +
  'window.CV_BLOB = ' + JSON.stringify(blob) + ';\n');

console.log(`wrote ${outPath}  (${ct.length} bytes ciphertext, ${ITER} PBKDF2 iters)`);
